    TASK_CALL_CAPABILITY_UNAVAILABLE = 'TASK_CALL_CAPABILITY_UNAVAILABLE',
    TASK_CALL_ADMISSION_HELD = 'TASK_CALL_ADMISSION_HELD',
    TASK_CALL_CLEANUP_UNCONFIRMED = 'TASK_CALL_CLEANUP_UNCONFIRMED',
    TASK_NOT_FOUND = 'TASK_NOT_FOUND',
